#!/usr/bin/env python3
"""Regenerate ``kolega_code/llm/specs/catalog/vercel_ai_gateway.py`` from Vercel AI Gateway.

Dev-time release chore, never imported by the CLI. Run it from the repo root:

    uv run python scripts/refresh_vercel_ai_gateway_catalog.py
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import subprocess
import sys
from pathlib import Path
from typing import Any, Optional, Sequence

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

OUTPUT_PATH = REPO_ROOT / "kolega_code" / "llm" / "specs" / "catalog" / "vercel_ai_gateway.py"
GENERATOR_REL_PATH = "scripts/refresh_vercel_ai_gateway_catalog.py"

if not OUTPUT_PATH.exists():
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(
        f"# Placeholder written by {GENERATOR_REL_PATH}; rerun it to populate.\nVERCEL_AI_GATEWAY_SPECS: dict = {{}}\n",
        encoding="utf-8",
    )

from kolega_code.config import ModelProvider  # noqa: E402
from kolega_code.llm.specs import vercel_ai_gateway_catalog as catalog  # noqa: E402


def _default_model() -> str:
    from kolega_code.cli.provider_registry import PROVIDER_DEFAULT_MODEL

    return PROVIDER_DEFAULT_MODEL[ModelProvider.VERCEL_AI_GATEWAY]


def _load_payload(source: Optional[str]) -> Any:
    if source:
        return json.loads(Path(source).read_text(encoding="utf-8"))
    return catalog.fetch_models()


def _header_lines(*, entry_count: int, featured_count: int, snapshot_date: str) -> list[str]:
    return [
        f"Generated by {GENERATOR_REL_PATH} — do not edit by hand.",
        "",
        f"Models:  {catalog.MODELS_URL} (snapshot {snapshot_date})",
        "Pricing: decimal-string gateway rates and input-tier schedules; paid routes are not endpoint-pinned.",
        "",
        f"{entry_count} tool-capable models, {featured_count} featured.",
        "Featured models are the ones every picker and the sub-agent model catalog",
        "show; the rest stay selectable by id (--model, /model, settings.json).",
        "",
        f"Regenerate with: uv run python {GENERATOR_REL_PATH}",
    ]


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--models-file", help="Read the /v1/models payload from a local JSON file.")
    parser.add_argument("--output", default=str(OUTPUT_PATH), help="Destination module path.")
    parser.add_argument("--skip-format", action="store_true", help="Do not run ruff format on the output.")
    args = parser.parse_args(argv)

    print(f"Reading {args.models_file}" if args.models_file else f"Fetching {catalog.MODELS_URL} ...")
    try:
        models_payload = _load_payload(args.models_file)
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: could not read the Vercel AI Gateway model list: {exc}", file=sys.stderr)
        return 1

    default_model = _default_model()
    try:
        entries = catalog.catalog_entries(models_payload)
    except catalog.VercelAIGatewayCatalogError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    featured = catalog.featured_ids(entries, always_include=[default_model])
    featured_set = set(featured)
    rendered_entries = [
        (identifier, {**spec, "featured": True} if identifier in featured_set else spec) for identifier, spec in entries
    ]

    source = catalog.render_catalog_module(
        rendered_entries,
        header_lines=_header_lines(
            entry_count=len(rendered_entries),
            featured_count=len(featured_set),
            snapshot_date=dt.date.today().isoformat(),
        ),
    )

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(source, encoding="utf-8")
    print(f"\nWrote {output} ({len(rendered_entries)} models, {len(featured_set)} featured).")

    if not args.skip_format:
        result = subprocess.run(["uv", "run", "ruff", "format", str(output)], cwd=REPO_ROOT)
        if result.returncode != 0:
            print("WARNING: ruff format failed; format the generated file manually.", file=sys.stderr)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
